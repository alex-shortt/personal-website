"""Transfer the reference alpha silhouette into a filled, sculptable volume.
Requires NumPy, SciPy and Pillow. X points right, Y up, Z toward the front camera.
The front outline is constrained by the image; depth is an explicit approximation.
"""
from pathlib import Path
import json
import numpy as np
from PIL import Image
from scipy.ndimage import binary_fill_holes, distance_transform_edt, label, map_coordinates

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'public/cloud'
BOUNDS = (2.05, 1.2, 1.55)  # Matches studio.cloudBounds and the shader.
SIZE = (512, 320)
WORLD_WIDTH = 3.6

alpha = np.asarray(Image.open(ROOT / 'public/pfp-transparent-cropped.png').convert('RGBA'))[:, :, 3]
mask = alpha >= 128
labels, _ = label(mask)
counts = np.bincount(labels.ravel())
keep = counts >= 64
keep[0] = False
mask = binary_fill_holes(keep[labels])
ys, xs = np.nonzero(mask)
bounds = [int(xs.min()), int(ys.min()), int(xs.max() + 1), int(ys.max() + 1)]
x0, y0, x1, y1 = bounds
units_per_pixel = WORLD_WIDTH / (x1 - x0)
center = ((x0 + x1 - 1) / 2, (y0 + y1 - 1) / 2)
signed = (distance_transform_edt(mask) - distance_transform_edt(~mask)) * units_per_pixel

# Texture rows run bottom to top for direct typed-array WebGL uploads.
x = np.linspace(-BOUNDS[0], BOUNDS[0], SIZE[0])
y = np.linspace(-BOUNDS[1], BOUNDS[1], SIZE[1])
xx, yy = np.meshgrid(x, y)
source_x = xx / units_per_pixel + center[0]
source_y = center[1] - yy / units_per_pixel
outline = map_coordinates(signed, [source_y, source_x], order=1, mode='constant', cval=-.125)

# Broad section constraints only. Individual billows are generated by the
# runtime 3D density field, not by hand-authored front/back surface mounds.
inside = np.maximum(outline, 0)

def smoothstep(low, high, v):
    t = np.clip((v-low)/(high-low), 0, 1)
    return t*t*(3-2*t)

def coherent_field(seed, wavelengths):
    # Low-frequency variation in world space. Independent seeds for depth
    # position and thickness avoid moving a uniformly thin sheet around.
    rng = np.random.default_rng(seed)
    field = np.zeros_like(xx)
    for wavelength in wavelengths:
        angle, phase = rng.uniform(0, 2*np.pi, 2)
        direction = xx*np.cos(angle) + yy*np.sin(angle)
        field += np.sin(direction*2*np.pi/wavelength + phase)
    return field / max(np.max(np.abs(field)), 1e-6)

upper_bank = smoothstep(-.32, -.04, yy)
position_noise = coherent_field(921, [2.8, 2.1, 1.65, 1.25])
thickness_noise = coherent_field(517, [2.5, 1.8, 1.35, .95])
# A broad ellipsoidal support gives the top view genuine depth, while 3D
# density noise still creates the visible billows within this loose container.
length_profile = np.sqrt(np.clip(1-(xx/1.90)**2, 0, 1))
half_depth = (.20 + .80*length_profile) * (.82 + .18*upper_bank)
half_depth *= 1 + .20*thickness_noise
center_z = -.035 + .15*upper_bank + .34*position_noise
# Recess the upper bank's front shoulder without flattening the rear volume.
# Splitting the correction between depth and center keeps the back face fixed.
front_recess = .42 * smoothstep(-.38, .14, yy) * length_profile
half_depth -= front_recess * .5
center_z -= front_recess * .5
# Stagger the upper shoulder across X: vary both its turning height and its
# depth, so the top does not meet one long, aligned face.
shoulder_wave = .11*np.sin(xx*3.8+.6) + .055*np.sin(xx*6.3-1.1)
upper_rounding = smoothstep(.02+shoulder_wave, .58+shoulder_wave, yy)
half_depth *= 1 - .24*upper_rounding
center_z += upper_bank * (.14*np.sin(xx*3.8+.6) + .055*np.sin(xx*6.3-1.1))
# The lower bank contracts on both depth faces before reaching its outline.
# Leave the core full and taper the shoulder, rather than flattening the row.
lower_bank = 1-smoothstep(-.42,-.12,yy)
lower_taper = 1-smoothstep(.025,.30,inside)
half_depth *= 1 - .30*lower_bank*lower_taper
# Position variation deliberately persists at the silhouette boundary.

upper_wisp = (1-smoothstep(300,365,source_x)) * (1-smoothstep(125,175,source_y))
lower_wisp = smoothstep(735,800,source_x) * smoothstep(390,425,source_y)
side_wisp = (1-smoothstep(310,345,source_x)) * smoothstep(365,395,source_y)
wisp = np.maximum.reduce([upper_wisp, lower_wisp, side_wisp])
wisp_depth = .10 + .045 * np.sqrt(np.clip(inside/.055, 0, 1))
half_depth = half_depth*(1-wisp) + wisp_depth*wisp
center_z *= 1-.15*wisp
assert np.max(half_depth + np.abs(center_z)) < BOUNDS[2]
assert np.max(np.abs(center_z)) < .65

# R: signed planar distance [-.125,.5]; G: half-depth [0,1.55];
# B: center depth [-.65,.65]; A must remain opaque for lossless canvas decoding.
texture = np.empty((*xx.shape, 4), dtype=np.uint8)
texture[:, :, 0] = np.round((np.clip(outline, -.125, .5) + .125) * 255 / .625)
texture[:, :, 1] = np.round(np.clip(half_depth / BOUNDS[2], 0, 1) * 255)
texture[:, :, 2] = np.round((center_z + .65) / 1.3 * 255)
texture[:, :, 3] = 255
Image.fromarray(texture).save(OUT / 'shape-profile.png', optimize=True)
Image.fromarray((mask * 255).astype(np.uint8)).save(OUT / 'reference-mask.png', optimize=True)
metadata = {
    'source': '/pfp-transparent-cropped.png',
    'alphaThreshold': 128, 'minimumComponentPixels': 64, 'fillInteriorHoles': True,
    'sourceBounds': bounds, 'sourceCenter': center, 'unitsPerPixel': units_per_pixel,
    'worldWidth': WORLD_WIDTH, 'worldHeight': (y1-y0) * units_per_pixel,
    'volumeBounds': BOUNDS, 'textureSize': SIZE,
    'depthIsInferred': True,
    'sculpt': {'method': 'silhouette-constrained procedural 3D density',
               'frontShoulderRecess': .42,
               'upperRounding': .24, 'lowerShoulderTaper': .30,
               'positionNoiseAmplitude': .34, 'thicknessNoiseAmplitude': .20,
               'maximumDepthExtent': float(np.max(half_depth + np.abs(center_z))),
               'wispDepthRange': [.20, .29]},
}
(OUT / 'shape-reference.json').write_text(json.dumps(metadata, indent=2) + '\n')
print(json.dumps({'textureBytes': (OUT / 'shape-profile.png').stat().st_size,
                  'maskPixels': int(mask.sum()), 'worldSize': [WORLD_WIDTH, metadata['worldHeight']]}))
